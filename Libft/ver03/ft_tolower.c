/** error log 
 *
 * (1) man ascii 해서 나오는 첫번째 set는 octal(8진수) 이다...
 *
 * */

int	ft_tolower(int c)
{
	if (c >= 'A' && c <= 'Z')
		return (c + 040);
	else
		return (c);
}
