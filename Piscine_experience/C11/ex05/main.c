#include "mylib.h"

int	main(int argc, char *argv[])
{
	if (argc != 4)
		return (0);
	if ((argv[2][0] != '+' && argv[2][0] != '-' \
				&& argv[2][0] != '*' && argv[2][0] != '%'\
				&& argv[2][0] != '/') \
			|| argv[2][1] != '\0')
	{
		write(1, "0\n", 2);
		return (0);
	}
	else
		do_operator(ft_atoi(argv[1]), ft_atoi(argv[3]), argv[2]);
	return (0);
}
