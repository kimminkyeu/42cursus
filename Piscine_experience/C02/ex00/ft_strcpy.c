char	*ft_strcpy(char *dest, char *src)
{
	char	*tmp;

	tmp = dest;
	while (*src != '\0')
	{
		*tmp = *src;
		++tmp;
		++src;
	}
	if (*src == '\0')
	{
		*tmp = *src;
	}
	return (dest);
}
